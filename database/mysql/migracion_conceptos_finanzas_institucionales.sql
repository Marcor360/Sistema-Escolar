-- Alta no destructiva del catálogo institucional: conserva claves y tarifas existentes.
-- Montos pendientes de autorización; sin recargos automáticos hasta configurar Finanzas.
INSERT INTO conceptos_pago (clave, nombre, tipo, monto_base, aplica_recargo, activo)
SELECT nuevos.clave, nuevos.nombre, nuevos.tipo, 0.00, 0, 1
FROM (
  SELECT '001' AS clave, 'INSCRIPCIÓN' AS nombre, 'INSCRIPCION' AS tipo
  UNION ALL SELECT '002', 'REINSCRIPCIÓN', 'INSCRIPCION'
  UNION ALL SELECT '003', 'REINCORPORACIÓN', 'OTRO'
  UNION ALL SELECT '004', 'EQUIVALENCIA', 'OTRO'
  UNION ALL SELECT '005', 'COLEGIATURA DE ENERO', 'COLEGIATURA'
  UNION ALL SELECT '006', 'COLEGIATURA DE FEBRERO', 'COLEGIATURA'
  UNION ALL SELECT '007', 'COLEGIATURA DE MARZO', 'COLEGIATURA'
  UNION ALL SELECT '008', 'COLEGIATURA DE ABRIL', 'COLEGIATURA'
  UNION ALL SELECT '009', 'COLEGIATURA DE MAYO', 'COLEGIATURA'
  UNION ALL SELECT '010', 'COLEGIATURA DE JUNIO', 'COLEGIATURA'
  UNION ALL SELECT '011', 'COLEGIATURA DE JULIO', 'COLEGIATURA'
  UNION ALL SELECT '012', 'COLEGIATURA DE AGOSTO', 'COLEGIATURA'
  UNION ALL SELECT '013', 'COLEGIATURA DE SEPTIEMBRE', 'COLEGIATURA'
  UNION ALL SELECT '014', 'COLEGIATURA DE OCTUBRE', 'COLEGIATURA'
  UNION ALL SELECT '015', 'COLEGIATURA DE NOVIEMBRE', 'COLEGIATURA'
  UNION ALL SELECT '016', 'COLEGIATURA DE DICIEMBRE', 'COLEGIATURA'
  UNION ALL SELECT '017', 'CUATRIMESTRE COMPLETO', 'OTRO'
  UNION ALL SELECT '018', 'ANUALIDAD', 'OTRO'
  UNION ALL SELECT '019', 'GRADO ACADÉMICO COMPLETO', 'OTRO'
  UNION ALL SELECT '020', 'CONSTANCIA DE ESTUDIOS', 'OTRO'
  UNION ALL SELECT '021', 'CONSTANCIA DE ESTUDIOS URGENTE', 'OTRO'
  UNION ALL SELECT '022', 'CONSTANCIA ESPECIAL', 'OTRO'
  UNION ALL SELECT '023', 'CONSTANCIA RENOVACIÓN DE BECA', 'OTRO'
  UNION ALL SELECT '024', 'CREDENCIAL ESTUDIANTIL CREDENCIAL', 'OTRO'
  UNION ALL SELECT '025', 'CREDENCIAL ESTUDIANTIL ANUAL', 'OTRO'
  UNION ALL SELECT '026', 'HISTORIAL ACADÉMICO POR CUATRIMESTRE', 'OTRO'
  UNION ALL SELECT '027', 'HISTORIAL ACADÉMICO POR SEMESTRE', 'OTRO'
  UNION ALL SELECT '028', 'SERVICIO SOCIAL', 'OTRO'
  UNION ALL SELECT '029', 'PRÁCTICAS PROFESIONALES', 'OTRO'
  UNION ALL SELECT '030', 'EXAMEN EXTRAORDINARIO', 'OTRO'
  UNION ALL SELECT '031', 'MATERIA LIBRE', 'OTRO'
  UNION ALL SELECT '032', 'REIMPRESIÓN DE BOLETA', 'OTRO'
  UNION ALL SELECT '033', 'GASTOS ADMINISTRATIVOS', 'OTRO'
  UNION ALL SELECT '034', 'CAMBIO DE TURNO', 'OTRO'
  UNION ALL SELECT '035', 'CAMBIO DE CARRERA', 'OTRO'
  UNION ALL SELECT '036', 'BAJA TEMPORAL', 'OTRO'
  UNION ALL SELECT '037', 'BAJA DEFINITIVA', 'OTRO'
) AS nuevos
WHERE NOT EXISTS (SELECT 1 FROM conceptos_pago AS actual WHERE actual.clave = nuevos.clave);
