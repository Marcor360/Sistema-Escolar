import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, expect, it, vi } from 'vitest';
import Login from './Login';
import { api } from '../api/client';
vi.mock('../auth/AuthContext', () => ({ useAuth: () => ({ login: vi.fn() }) }));
vi.mock('../marca/MarcaContext', () => ({ useMarca: () => ({ marca: { nombreInstitucion: 'Escuela', logoUrl: null } }) }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('solicita activación sin acreditar entrega, conserva errores y vuelve al login tras activar', async () => {
  const post = vi.spyOn(api, 'post').mockResolvedValueOnce({ data: { mensaje: 'Si está pendiente recibirás instrucciones' } });
  render(<MemoryRouter><Login /></MemoryRouter>);
  fireEvent.click(screen.getByRole('button', { name: 'Activar mi cuenta por primera vez' }));
  fireEvent.change(screen.getByLabelText('Correo institucional del alumno'), { target: { value: 'alumno@example.test' } });
  fireEvent.click(screen.getByRole('button', { name: 'Solicitar código de activación' }));
  await screen.findByLabelText('Código de activación (64 caracteres)');
  expect(post).toHaveBeenCalledWith('/auth/solicitar-activacion', { email: 'alumno@example.test' });
  expect(screen.getByRole('status').textContent).toContain('Si está pendiente');
  fireEvent.change(screen.getByLabelText('Código de activación (64 caracteres)'), { target: { value: 'A'.repeat(64) } });
  fireEvent.change(screen.getByLabelText('Nueva contraseña (mínimo 8 caracteres)'), { target: { value: 'Nueva_Segura_42!' } });
  post.mockRejectedValueOnce(new Error('Código vencido'));
  fireEvent.click(screen.getByRole('button', { name: 'Activar mi cuenta' }));
  await screen.findByRole('alert');
  expect(screen.getByLabelText('Código de activación (64 caracteres)')).toBeTruthy();
  post.mockResolvedValueOnce({ data: { mensaje: 'Cuenta activada. Inicia sesión.' } });
  fireEvent.click(screen.getByRole('button', { name: 'Activar mi cuenta' }));
  await waitFor(() => expect(screen.getByRole('button', { name: 'Entrar' })).toBeTruthy());
  expect(post).toHaveBeenLastCalledWith('/auth/activar-cuenta', { token: 'a'.repeat(64), password: 'Nueva_Segura_42!' });
  expect(screen.getByRole('status').textContent).toContain('Cuenta activada');
});
